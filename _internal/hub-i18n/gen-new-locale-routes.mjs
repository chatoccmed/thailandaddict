// Regenerate pages/{zh,ru,ko,ja,hi,he,ar}/[slug].astro to dispatch review/roundup/article
// (was articles-only). Idempotent — overwrites with the current template.
//
// 2026-09-09: the template no longer uses content collections. It reads one entry from disk at
// render time via src/lib/content-fs.ts, and getStaticPaths props carry ONLY { kind, dir,
// availableLocales } — never the data object. That is the load-bearing part: putting `data` back
// into props re-materialises all 19,530 entries in memory and restores the build ceiling this
// change removed. See _internal/BUILD-ROOTCAUSE-2026-09.md §5. If you edit this template, keep
// the nine route files in step by re-running it — including src/pages/[slug].astro and
// src/pages/en/[slug].astro, which this script does NOT write (they have their own locale logic).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');

const LANGS = ['zh', 'ru', 'ko', 'ja', 'hi', 'he', 'ar'];

const tpl = (code) => `---
// /${code}/ pages. Reads its one entry from disk at render time — content collections were retired
// 2026-09-09 (_internal/BUILD-ROOTCAUSE-2026-09.md §5). props carry only what is needed to LOCATE
// the entry; putting \`data\` back in props re-materialises all 19,530 entries in memory and brings
// the build ceiling back. Generated by _internal/hub-i18n/gen-new-locale-routes.mjs — edit there.
import { slugsOf, readEntry } from '../../lib/content-fs';
import ReviewLayout from '../../layouts/ReviewLayout.astro';
import RoundupLayout from '../../layouts/RoundupLayout.astro';
import ArticleLayout from '../../layouts/ArticleLayout.astro';
import { extraLocalesBySlug, extraReviewLocalesBySlug, extraRoundupLocalesBySlug } from '../../lib/locales';

export async function getStaticPaths() {
  const extra = await extraLocalesBySlug();
  const extraRv = await extraReviewLocalesBySlug();
  const extraRd = await extraRoundupLocalesBySlug();
  return [
    ...slugsOf('reviews-${code}').map((slug) => ({
      params: { slug },
      props: { kind: 'review' as const, dir: 'reviews-${code}', availableLocales: ['th', 'en', ...(extraRv[slug] || [])] },
    })),
    ...slugsOf('roundups-${code}').map((slug) => ({
      params: { slug },
      props: { kind: 'roundup' as const, dir: 'roundups-${code}', availableLocales: ['th', 'en', ...(extraRd[slug] || [])] },
    })),
    ...slugsOf('articles-${code}').map((slug) => ({
      params: { slug },
      props: { kind: 'article' as const, dir: 'articles-${code}', availableLocales: ['th', 'en', ...(extra[slug] || [])] },
    })),
  ];
}

const { kind, dir, availableLocales } = Astro.props;
const data = readEntry(dir, Astro.params.slug!);   // one entry live at a time
---
{kind === 'review'
  ? <ReviewLayout data={data} lang="${code}" availableLocales={availableLocales} />
  : kind === 'roundup'
  ? <RoundupLayout data={data} lang="${code}" availableLocales={availableLocales} />
  : <ArticleLayout data={data} lang="${code}" hasEn={true} availableLocales={availableLocales} />}
`;

for (const code of LANGS) {
  const file = path.join(ROOT, 'astro', 'src', 'pages', code, '[slug].astro');
  fs.writeFileSync(file, tpl(code));
  console.log('wrote', path.relative(ROOT, file));
}
