#!/usr/bin/env node
/* =============================================================================
   gen-duplicate-redirects.mjs — 301s for the review pages merged into one

   Owns ONE block at the end of astro/public/_redirects, marked by the line
   below. Everything above it belongs to gen-redirects.mjs (the WordPress
   cutover splats), and _internal/bulk-redirects.csv is never touched — that
   file is uploaded to Cloudflare Bulk Redirects by hand and gen-redirects.mjs
   currently cannot run at all (its migration manifest is no longer in the
   repo), so regenerating it here would silently shrink it.

   Source of truth: _internal/duplicate-reviews.json (the owner's decision).
   For every merged page, in every locale it existed in:
     /<slug>       → the page that stayed, in that locale when it is translated
     /<slug>.html    there, otherwise the English page
   and the hotel taken down points at its province hotel list. Both URL shapes
   are emitted because internal links carry .html while the clean URL is what
   the site advertises. Static rules do not count against the 100 dynamic-rule
   limit; Cloudflare allows 2,000 of them.

   A page that still exists on disk is never redirected — the rule would shadow
   a live page — so run this AFTER merge-duplicate-reviews.mjs --apply.

   Dry run by default. Usage: node _internal/gen-duplicate-redirects.mjs [--apply]
   ========================================================================== */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const APPLY = process.argv.includes('--apply');
const MARK = '# --- duplicate review pages · generated by _internal/gen-duplicate-redirects.mjs ---';
const FILE = path.join(ROOT, 'astro/public/_redirects');
const doc = JSON.parse(fs.readFileSync(path.join(ROOT, '_internal/duplicate-reviews.json'), 'utf8'));

const dirOf = (loc) => path.join(ROOT, 'astro/src/content', loc === 'th' ? 'reviews' : `reviews-${loc}`);
const has = (loc, slug) => fs.existsSync(path.join(dirOf(loc), `${slug}.json`));
const prefix = (loc) => (loc === 'th' ? '' : `/${loc}`);
const rules = [], shadowed = [], noTarget = [];
const add = (loc, slug, target) => {
  if (has(loc, slug)) { shadowed.push(`${prefix(loc)}/${slug}`); return; }
  rules.push([`${prefix(loc)}/${slug}`, target]);
};
for (const g of doc.groups || []) {
  for (const [slug, locs] of Object.entries(g.redirectLocales || {})) {
    for (const loc of locs) {
      if (!has(loc, g.keep) && !has('en', g.keep)) { noTarget.push(`${prefix(loc)}/${slug} → ${g.keep}`); continue; }
      add(loc, slug, has(loc, g.keep) ? `${prefix(loc)}/${g.keep}` : `/en/${g.keep}`);
    }
  }
}
for (const r of doc.removed || []) for (const loc of r.locales || ['th']) add(loc, r.slug, `${prefix(loc)}${r.to}`);

const lines = rules.flatMap(([src, tgt]) => [`${src} ${tgt} 301`, `${src}.html ${tgt} 301`]);
const raw = fs.readFileSync(FILE, 'utf8');
const head = raw.split(MARK)[0].replace(/\s*$/, '\n');
const body = lines.length
  ? `${MARK}\n# One property, one page (owner decision ${doc.decided}). Source: _internal/duplicate-reviews.json\n${lines.join('\n')}\n`
  : '';
const out = head + body;

console.log(`${APPLY ? 'writing' : 'dry run'} · pages redirected ${rules.length} · rules ${lines.length} (clean URL + .html) · kept above the marker: ${head.trimEnd().split('\n').length} line(s)`);
if (shadowed.length) console.log(`  skipped, the page still exists (run the merge first): ${shadowed.length} — ${shadowed.slice(0, 5).join(', ')}${shadowed.length > 5 ? ' …' : ''}`);
if (noTarget.length) console.log(`  ⚠ no target page on disk: ${noTarget.join(', ')}`);
if (out === raw) { console.log('_redirects already matches'); process.exit(0); }
if (APPLY) { fs.writeFileSync(FILE, out); console.log(`wrote ${path.relative(ROOT, FILE)} · ${out.split('\n').length} lines`); }
else console.log('DRY RUN — nothing written. Re-run with --apply.');
