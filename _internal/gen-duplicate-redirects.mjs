#!/usr/bin/env node
/* =============================================================================
   gen-duplicate-redirects.mjs — 301s for the review pages merged into one

   Writes worker-redirects.js at the repo root: one map from every merged page's
   path to the page that stayed, which worker.js answers with a 301.

   ── WHY NOT _redirects (learned the hard way, 2026-09-16) ───────────────────
   These 260 rules lived in astro/public/_redirects first, on the belief —
   written into this file's own header and into CLAUDE.md — that a rule without
   a wildcard is "static" and draws on a 2,000-rule allowance rather than the
   100-rule dynamic one. The deploy proved that false:

       Invalid _redirects configuration:
       Line 108: Maximum number of dynamic _redirects rules limit of 100
       exceeded [code: 100324]

   Line 108 holds the 101st rule in the file, counting the plain path-to-path
   ones. Cloudflare counts EVERY rule against the 100 limit here, so no amount
   of splitting or reordering would have fit 260 of them. The deploy failed
   outright — assets uploaded, Worker version rejected, production untouched.

   The Worker has no such quota. Static assets are served before it runs, so a
   page that still exists is never shadowed by a redirect (the guard below is
   kept anyway, so the map never contradicts the build), and a merged page —
   whose file the merge deleted — is no longer an asset and reaches the Worker.

   _internal/bulk-redirects.csv is still never touched: it is uploaded to
   Cloudflare Bulk Redirects by hand, and gen-redirects.mjs cannot run at all
   (its migration manifest is no longer in the repo), so regenerating it here
   would silently shrink it.

   Sources of truth: _internal/duplicate-reviews.json (the owner's decision
   about duplicate pages) and _internal/renamed-slugs.json (pages that kept
   existing under a different URL — a rename is not a duplicate, so it gets its
   own file rather than diluting the decision record).
   For every merged page, in every locale it existed in:
     /<loc>/<slug> → the page that stayed, in that locale when it is translated
                     there, otherwise the English page
   and the hotel taken down points at its province hotel list. Only the clean
   path is stored; worker.js strips a trailing .html before the lookup, so both
   URL shapes redirect from half the entries.

   A page that still exists on disk is never redirected — the rule would shadow
   a live page — so run this AFTER merge-duplicate-reviews.mjs --apply.

   Dry run by default. Usage: node _internal/gen-duplicate-redirects.mjs [--apply]
   ========================================================================== */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const APPLY = process.argv.includes('--apply');
const MARK = '# --- duplicate review pages · generated by _internal/gen-duplicate-redirects.mjs ---';
const REDIR = path.join(ROOT, 'astro/public/_redirects');
const OUT = path.join(ROOT, 'worker-redirects.js');
const doc = JSON.parse(fs.readFileSync(path.join(ROOT, '_internal/duplicate-reviews.json'), 'utf8'));

const dirOf = (loc) => path.join(ROOT, 'astro/src/content', loc === 'th' ? 'reviews' : `reviews-${loc}`);
const has = (loc, slug) => fs.existsSync(path.join(dirOf(loc), `${slug}.json`));
const prefix = (loc) => (loc === 'th' ? '' : `/${loc}`);
const rules = [], shadowed = [], noTarget = [];
const add = (loc, slug, target) => {
  if (has(loc, slug)) { shadowed.push(`${prefix(loc)}/${slug}`); return; }
  rules.push([`${prefix(loc)}/${slug}`, target]);
};
for (const g of doc.groups || []) {
  for (const [slug, locs] of Object.entries(g.redirectLocales || {})) {
    for (const loc of locs) {
      if (!has(loc, g.keep) && !has('en', g.keep)) { noTarget.push(`${prefix(loc)}/${slug} → ${g.keep}`); continue; }
      add(loc, slug, has(loc, g.keep) ? `${prefix(loc)}/${g.keep}` : `/en/${g.keep}`);
    }
  }
}
for (const r of doc.removed || []) for (const loc of r.locales || ['th']) add(loc, r.slug, `${prefix(loc)}${r.to}`);
/* Pages that kept existing under a different URL (_internal/renamed-slugs.json).
   A rename is not a duplicate, so it lives in its own file — but it needs the
   same thing from the reader's side: the old URL must go on working forever. */
const renamedFile = path.join(ROOT, '_internal/renamed-slugs.json');
let renamed = 0;
if (fs.existsSync(renamedFile)) {
  for (const r of JSON.parse(fs.readFileSync(renamedFile, 'utf8')).renamed || []) {
    for (const loc of r.locales || ['th']) { add(loc, r.from, `${prefix(loc)}/${r.to}`); renamed++; }
  }
}
rules.sort((a, b) => a[0].localeCompare(b[0]));

const module_ = `// GENERATED by _internal/gen-duplicate-redirects.mjs — do not edit by hand.
// Sources: _internal/duplicate-reviews.json (one property, one page — owner
// decision ${doc.decided}) and _internal/renamed-slugs.json (pages that kept
// existing under a different URL).
//
// Every key is a URL that no longer serves a page; the value is where that
// page's content lives now. worker.js strips a trailing ".html" before the
// lookup, so both URL shapes a reader can arrive on are covered by one entry.
//
// These are NOT in astro/public/_redirects on purpose: Cloudflare counts every
// rule in that file against a 100-rule limit, and a deploy with ${rules.length * 2} of them
// was rejected outright (code 100324). The Worker has no such quota.
export const MOVED_PAGES = {
${rules.map(([src, tgt]) => `  ${JSON.stringify(src)}: ${JSON.stringify(tgt)},`).join('\n')}
};
`;

/* the rules move out of _redirects: drop the block this script used to own */
const raw = fs.readFileSync(REDIR, 'utf8');
const head = raw.split(MARK)[0].replace(/\s*$/, '\n');
const hadBlock = raw.includes(MARK);
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';

console.log(`${APPLY ? 'writing' : 'dry run'} · pages redirected ${rules.length} (${rules.length - renamed} merged/removed · ${renamed} renamed) · URL shapes covered ${rules.length * 2} (clean + .html)`);
console.log(`  worker-redirects.js: ${prev === module_ ? 'already matches' : `${prev ? 'updated' : 'new'} · ${module_.split('\n').length} lines`}`);
console.log(`  _redirects: ${hadBlock ? `removing the ${raw.split('\n').length - head.split('\n').length} generated line(s)` : 'no generated block present'} · ${head.trimEnd().split('\n').length} line(s) kept`);
const staticRules = head.split('\n').filter((l) => l.startsWith('/')).length;
console.log(`  _redirects rules after this: ${staticRules} — Cloudflare's limit is 100`);
if (staticRules > 100) { console.log('  ✗ still over the limit'); process.exit(1); }
if (shadowed.length) console.log(`  skipped, the page still exists (run the merge first): ${shadowed.length} — ${shadowed.slice(0, 5).join(', ')}${shadowed.length > 5 ? ' …' : ''}`);
if (noTarget.length) console.log(`  ⚠ no target page on disk: ${noTarget.join(', ')}`);
if (APPLY) {
  fs.writeFileSync(OUT, module_);
  if (hadBlock) fs.writeFileSync(REDIR, head);
  console.log(`wrote worker-redirects.js${hadBlock ? ' and trimmed _redirects' : ''}`);
} else console.log('DRY RUN — nothing written. Re-run with --apply.');
