function relatedFor(slug) {
  const i = ORDER.indexOf(slug);
  const sibs = [ORDER[(i + 1) % ORDER.length], ORDER[(i + 2) % ORDER.length], ORDER[(i + 3) % ORDER.length]];
  return { th: [{ href: CRUMB_HREF, title: '🧭 ศูนย์รวมคู่มือเตรียมตัวเที่ยวไทย' }, ...sibs.map((s) => ({ href: `${s}.html`, title: SIB[s].th }))],
           en: [{ href: CRUMB_HREF, title: '🧭 Plan Your Trip hub' }, ...sibs.map((s) => ({ href: `${s}.html`, title: SIB[s].en }))] };
}
function toBlocks(spec, loc) {
  return spec.blocks.map((b) => {
    if (b.k === 'p') return { kind: 'p', html: b[loc] };
    if (b.k === 'h2') return { kind: 'h2', text: b[loc], ...(b.id ? { id: b.id } : {}) };
    if (b.k === 'list') return { kind: 'list', items: b[loc] };
    if (b.k === 'tip') return { kind: 'tip', ...(b.t ? { title: b.t[loc] } : {}), html: b[loc] };
    if (b.k === 'cta') return { kind: 'cta', text: b[loc].text, href: b[loc].href, label: b[loc].label };
    if (b.k === 'table') return { kind: 'table', ...(b.cap ? { caption: b.cap[loc] } : {}), headers: b.h[loc], rows: b.r[loc] };
    throw new Error('unknown block ' + b.k);
  });
}
function buildArticle(spec, loc) {
  const m = spec[loc];
  const rel = relatedFor(spec.slug)[loc];
  const crumbCity = loc === 'en' ? 'Plan Your Trip' : 'เตรียมตัวเที่ยวไทย';
  return {
    slug: spec.slug, type: 'prep', cluster: 'thailand',
    title: m.title, metaDesc: m.metaDesc, keywords: m.keywords,
    ogTitle: m.title.split(' | ')[0], ogDesc: m.metaDesc,
    image: `/images/heroes/${spec.hero}.jpg`,
    crumbCity, crumbCityHref: CRUMB_HREF,
    regionLabel: '🇹🇭 Thailand', regionHref: 'country-thailand.html',
    eyebrow: m.eyebrow, h1: m.h1, heroEmoji: spec.emoji, heroImg: `/images/heroes/${spec.hero}.jpg`,
    intro: m.intro, chips: m.chips, readTime: m.read,
    publishedDate: DATE, modifiedDate: DATE,
    blocks: toBlocks(spec, loc),
    faq: spec.faq.map((f) => ({ q: f.q[loc], a: f.a[loc] })),
    related: rel,
  };
}

let n = 0; const leaks = [];
for (const spec of GUIDES) {
  const th = buildArticle(spec, 'th');
  const en = buildArticle(spec, 'en');
  // alignment + leak guards
  if (th.blocks.map((b) => b.kind).join() !== en.blocks.map((b) => b.kind).join()) throw new Error('block mismatch ' + spec.slug);
  const enStr = JSON.stringify({ ...en });
  // allow ฿ (U+0E3F) only; any other Thai letter in EN = leak
  if (/[ก-฾เ-๛]/.test(enStr)) leaks.push(spec.slug);
  fs.writeFileSync(path.join(A_TH, spec.slug + '.json'), JSON.stringify(th, null, 2) + '\n');
  fs.writeFileSync(path.join(A_EN, spec.slug + '.json'), JSON.stringify(en, null, 2) + '\n');
  n++;
}
console.log(JSON.stringify({ written: n, slugs: GUIDES.map((g) => g.slug), enThaiLeaks: leaks }, null, 2));
