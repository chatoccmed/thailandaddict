/* heroes/ and cities/ left the deploy bundle on 2026-09-26, and the worker has
   no R2 fallback: a /images/ path that is not in the bundle is a 404, not a
   redirect. The generators now print absolute R2 urls, but ~1,500 hub pages
   under astro/public/<lang>/ are not regenerated by the build — they are
   committed snapshots that localize.mjs wrote from the English DOM, months
   ago, and they still carry the old bundle paths.

   Re-running localize.mjs to fix a url prefix would re-translate 1,500 pages
   to change one string, and i18n coverage drops silently when that happens
   (CLAUDE.md). So this rewrites the prefix and nothing else.

   🚨 The obvious pattern is wrong. /images/heroes/ also appears INSIDE a url
   that is already correct — https://pub-….r2.dev/images/heroes/krabi.jpg —
   and rewriting that produces "r2.devhttps://…". A bare path is one that is
   not preceded by the tail of a host, so the lookbehind is the whole point of
   this script; the counts printed below separate the two so the difference is
   visible rather than assumed.

   Usage: node _internal/qa/rewrite-bundle-image-paths.mjs <dir> [--apply]
   Read-only without --apply; exits 1 when a bundle path is still there. */
import fs from 'node:fs';
import path from 'node:path';

const R2 = process.env.PUBLIC_IMG_BASE || 'https://pub-65cf98dcb15e4c06a7a465ec411b870a.r2.dev';
const DIR = process.argv[2];
const APPLY = process.argv.includes('--apply');
if (!DIR || !fs.existsSync(DIR)) { console.error('usage: node _internal/qa/rewrite-bundle-image-paths.mjs <dir> [--apply]'); process.exit(2); }

/* the image files themselves are not text and are not scanned */
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(d, e.name);
  return e.isDirectory() ? (e.name === 'images' ? [] : walk(p)) : [p];
});

const OURS = /https:\/\/thailandaddict\.com\/images\/(heroes|cities)\//g;
const BARE = /(?<![A-Za-z0-9._\/-])\/images\/(heroes|cities)\//g;
const ALREADY = new RegExp(R2.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\/images\\/(?:heroes|cities)\\/', 'g');
const fix = (s) => s.replace(OURS, R2 + '/images/$1/').replace(BARE, R2 + '/images/$1/');

const files = walk(DIR).filter((f) => /\.(html|js|css|json|xml|webmanifest)$/i.test(f));
let touched = 0, bare = 0, ours = 0, already = 0;
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8');
  already += (s.match(ALREADY) || []).length;
  const nb = (s.match(BARE) || []).length, no = (s.match(OURS) || []).length;
  if (!nb && !no) continue;
  touched++; bare += nb; ours += no;
  if (!APPLY) continue;
  const out = fix(s);
  /* the failure this script exists to avoid: one url carrying two hosts */
  if (/https?:\/\/[^\s"')]*https?:\/\//.test(out) && !/https?:\/\/[^\s"')]*https?:\/\//.test(s)) {
    console.error('a url with two hosts appeared in ' + f); process.exit(1);
  }
  fs.writeFileSync(f + '.tmp', out, 'utf8');
  if (fs.readFileSync(f + '.tmp', 'utf8') !== out) { console.error('readback mismatch: ' + f); process.exit(1); }
  fs.renameSync(f + '.tmp', f);
}
console.log(`${DIR}: ${files.length} text files scanned`);
console.log(`  already on R2 : ${already}`);
console.log(`  bundle paths  : ${bare} bare + ${ours} on our own domain, in ${touched} files`
  + (APPLY ? ' → rewritten' : ' (dry run — pass --apply)'));
process.exit(!APPLY && (bare + ours) ? 1 : 0);
