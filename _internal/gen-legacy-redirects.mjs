#!/usr/bin/env node
/* =============================================================================
   gen-legacy-redirects.mjs — the old WordPress URLs, answered by the Worker

   Reads _internal/bulk-redirects.csv (472 rows: every old WP URL, with and
   without its trailing slash) and writes worker-legacy-redirects.js at the repo
   root: one map from path (trailing slash stripped) to the new location, which
   worker.js answers with a 301 that keeps the query string.

   ── WHY THE WORKER, NOT CLOUDFLARE BULK REDIRECTS (2026-10-28) ──────────────
   Bulk Redirects are an ACCOUNT-level resource: they do not move with the zone.
   Moving thailandaddict.com from chatmaliwan to chatoccmed meant recreating
   them on the new account, which needs an API token with Account Filter Lists
   + Account Rulesets on that account. In the Worker they travel with every
   deploy, on any account, and the CSV stays the single source.

   ── THE PAGES THE REDIRECTS SHADOW ──────────────────────────────────────────
   Static assets are served BEFORE the Worker runs. A few old WP paths are now
   real pages too (e.g. /top10-hotels-pattaya), and Bulk Redirects, which run
   in front of everything, still send those visitors on. To keep exactly that
   behaviour, every such path must be listed in wrangler.jsonc
   assets.run_worker_first so the Worker sees it first. This script lists them
   in SHADOWED_ASSETS and fails if either wrangler config is missing one.

   Run after editing the CSV:  node _internal/gen-legacy-redirects.mjs
   ============================================================================= */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const rows = fs.readFileSync(path.join(ROOT, '_internal/bulk-redirects.csv'), 'utf8')
  .split(/\r?\n/).filter(Boolean).slice(1).map(l => l.split(','));

const map = {};
for (const [src, tgt, status] of rows) {
  if (status !== '301') throw new Error(`only 301s are supported, got ${status} for ${src}`);
  const key = new URL(src).pathname.replace(/\/$/, '');
  const t = new URL(tgt);
  if (t.host !== 'thailandaddict.com') throw new Error(`target leaves the site: ${tgt}`);
  const val = t.pathname + t.search;
  if (!key) throw new Error(`a redirect of the home page is not allowed: ${src}`);
  if (map[key] && map[key] !== val) throw new Error(`${key} has two targets: ${map[key]} and ${val}`);
  if (key === val.replace(/\/$/, '')) throw new Error(`self-loop: ${src}`);
  map[key] = val;
}

// Paths that are also a built page: the Worker must run first for these.
const dist = path.join(ROOT, 'astro/dist');
if (!fs.existsSync(dist)) throw new Error('astro/dist is missing; build first so shadowed pages can be found');
const isFile = p => fs.existsSync(p) && fs.statSync(p).isFile();
const shadowed = [];
for (const k of Object.keys(map).sort())
  if ([k + '.html', k + '/index.html'].some(f => isFile(path.join(dist, f)))) shadowed.push(k, k + '/');

const body = Object.keys(map).sort().map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`).join('\n');
fs.writeFileSync(path.join(ROOT, 'worker-legacy-redirects.js'),
`// GENERATED by _internal/gen-legacy-redirects.mjs from _internal/bulk-redirects.csv — do not edit by hand.
// Old WordPress URLs → where that content lives now. worker.js strips a trailing "/" before the lookup.
// SHADOWED_ASSETS are also built pages; wrangler.jsonc assets.run_worker_first must list them.
export const LEGACY_WP = {
${body}
};
export const SHADOWED_ASSETS = ${JSON.stringify(shadowed)};
`);

let bad = 0;
for (const cfg of ['wrangler.jsonc', 'wrangler.A.jsonc']) {
  const f = path.join(ROOT, cfg);
  if (!fs.existsSync(f)) continue;
  const src = fs.readFileSync(f, 'utf8');
  if (/"run_worker_first"\s*:\s*true/.test(src)) continue;   // every request reaches the Worker
  const m = src.match(/"run_worker_first"\s*:\s*(\[[^\]]*\])/);
  const listed = new Set(m ? JSON.parse(m[1]) : []);
  const missing = shadowed.filter(p => !listed.has(p));
  if (missing.length) { bad++; console.error(`✗ ${cfg} assets.run_worker_first is missing: ${missing.join(' ')}`); }
}
console.log(`worker-legacy-redirects.js: ${Object.keys(map).length} paths from ${rows.length} CSV rows; ${shadowed.length / 2} shadow a built page`);
if (bad) process.exit(1);
