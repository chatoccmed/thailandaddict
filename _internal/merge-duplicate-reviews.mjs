#!/usr/bin/env node
/* =============================================================================
   merge-duplicate-reviews.mjs — one property, one page

   _internal/duplicate-reviews.json records the owner's decision (2026-09-16):
   for each hotel that was published twice, which review page stays, which
   pages merge into it, and the one hotel whose page comes down for good.

   This applies that decision to the content:
     · every reference to a merged page — related[].href, nextHref / prevHref,
       roundup entries[].reviewUrl, article links, breadcrumb URLs — points at
       the page that stayed, in every locale
     · a list that would then name the same page twice keeps the first mention
     · a page whose next/prev would point at itself loses that link
     · references to the REMOVED hotel are deleted rather than repointed: its
       roundup entry, its comparison row and its table-of-contents item go, and
       the ranks after it move up one
     · the merged and removed review files are deleted in every locale, and
       their rows in _internal/hotel-coords.json go with them
   Formatting is preserved through lib/json-format.mjs. Feeds, sitemap, hub
   pages and the near-me index are regenerated by prebuild from what is left,
   and the 301s come from gen-redirects.mjs, which reads the same decision file.

   Prose that counts the hotels ("12 hotels we reviewed") cannot be rewritten
   safely by a script, so every field that still names the old count is listed
   at the end for a human to edit.

   Dry run by default. Usage: node _internal/merge-duplicate-reviews.mjs [--apply]
   ========================================================================== */
import fs from 'node:fs';
import path from 'node:path';
import { serializeLike } from './lib/json-format.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const APPLY = process.argv.includes('--apply');
const doc = JSON.parse(fs.readFileSync(path.join(ROOT, '_internal/duplicate-reviews.json'), 'utf8'));
const to = new Map();
for (const g of doc.groups) for (const s of g.redirect) to.set(s, g.keep);
const gone = new Set((doc.removed || []).map((r) => r.slug));
const touched = [...to.keys(), ...gone];
if (!touched.length) { console.log('nothing to merge'); process.exit(0); }
const escape = (s) => s.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&');
const REF = new RegExp('(' + touched.map(escape).join('|') + ')(?![a-z0-9-])', 'g');
const bare = (href) => String(href || '').replace(/^.*\//, '').replace(/\.html$/, '').replace(/[#?].*$/, '');

const dirs = [];
const CONTENT = path.join(ROOT, 'astro/src/content');
for (const d of fs.readdirSync(CONTENT)) if (fs.statSync(path.join(CONTENT, d)).isDirectory()) dirs.push(path.join(CONTENT, d));

const walk = (node, fn) => {
  if (Array.isArray(node)) node.forEach((v, i) => { if (v && typeof v === 'object') walk(v, fn); else if (typeof v === 'string') node[i] = fn(v); });
  else if (node && typeof node === 'object') for (const [k, v] of Object.entries(node)) { if (v && typeof v === 'object') walk(v, fn); else if (typeof v === 'string') node[k] = fn(v); }
};
const drop = (arr, pred) => { const kept = arr.filter((x) => !pred(x)); const n = arr.length - kept.length; arr.length = 0; arr.push(...kept); return n; };

let changed = 0, repointed = 0, deduped = 0, selfRefs = 0, entriesRemoved = 0, listRows = 0;
const countNotes = [], leftovers = [];
for (const dir of dirs) {
  for (const name of fs.readdirSync(dir)) {
    if (!name.endsWith('.json')) continue;
    const file = path.join(dir, name);
    const self = name.slice(0, -5);
    if (to.has(self) || gone.has(self)) continue;           // this file is being deleted
    const raw = fs.readFileSync(file, 'utf8');
    if (!touched.some((s) => raw.includes(s))) continue;
    const data = JSON.parse(raw);

    /* 1. the removed hotel: take its rows out, then renumber what follows */
    if (gone.size) {
      const names = (data.entries || []).filter((e) => gone.has(bare(e.reviewUrl))).map((e) => e.name);
      if (names.length) {
        const before = data.entries.length;
        entriesRemoved += drop(data.entries, (e) => gone.has(bare(e.reviewUrl)));
        for (const key of ['toc', 'compareRows']) if (Array.isArray(data[key])) listRows += drop(data[key], (r) => names.includes(r.name));
        data.entries.forEach((e, i) => { if (e.rank !== undefined) e.rank = String(i + 1); });
        if (Array.isArray(data.toc)) data.toc.forEach((t, i) => { if (t.n !== undefined) t.n = String(i + 1); });
        if (Array.isArray(data.compareRows)) data.compareRows.forEach((r, i) => { if (r.rank !== undefined) r.rank = String(i + 1); });
        const old = new RegExp('(^|[^0-9])' + before + '([^0-9]|$)');
        for (const [k, v] of Object.entries(data)) if (typeof v === 'string' && old.test(v)) countNotes.push(`${path.relative(ROOT, file)} · ${k}`);
      }
      if (Array.isArray(data.related)) listRows += drop(data.related, (r) => gone.has(bare(r.href)));
      for (const k of ['nextHref', 'prevHref']) if (typeof data[k] === 'string' && gone.has(bare(data[k]))) delete data[k];
    }

    /* 2. merged pages: point every reference at the page that stayed */
    walk(data, (s) => s.replace(REF, (m) => { if (gone.has(m)) return m; repointed++; return to.get(m); }));

    /* 3. the same page twice in one list, or a page linking to itself */
    if (Array.isArray(data.related)) {
      const seen = new Set();
      deduped += drop(data.related, (r) => { const h = bare(r.href); if (!h) return false; if (h === self || seen.has(h)) return true; seen.add(h); return false; });
    }
    for (const k of ['nextHref', 'prevHref']) if (bare(data[k]) === self) { delete data[k]; selfRefs++; }

    const out = serializeLike(raw, data).text;
    if (out === raw) continue;
    JSON.parse(out);                                         // never write something that does not parse
    changed++;
    if (APPLY) fs.writeFileSync(file, out);
    /* a merged slug can be a PREFIX of the page it merges into
       (review-akyra-manor-chiang-mai → …-chiang-mai-chiang-mai), so the
       leftover test needs the same boundary the replacement used */
    const still = touched.filter((s) => new RegExp(escape(s) + '(?![a-z0-9-])').test(out));
    if (still.length) leftovers.push(`${path.relative(ROOT, file)} → ${still.join(', ')}`);
  }
}

/* 4. the merged and removed review files themselves */
let deleted = 0;
for (const dir of dirs) for (const slug of touched) {
  const f = path.join(dir, slug + '.json');
  if (!fs.existsSync(f)) continue;
  deleted++;
  if (APPLY) fs.rmSync(f);
}

/* 5. their store rows */
const storeFile = path.join(ROOT, '_internal/hotel-coords.json');
const storeRaw = fs.readFileSync(storeFile, 'utf8');
const store = JSON.parse(storeRaw);
let rows = 0;
for (const slug of touched) if (store[slug]) { delete store[slug]; rows++; }
if (APPLY && rows) fs.writeFileSync(storeFile, serializeLike(storeRaw, store).text);

console.log(`${APPLY ? 'applied' : 'dry run'} · content files changed ${changed} · references repointed ${repointed} · duplicate list rows dropped ${deduped} · self links removed ${selfRefs}`);
console.log(`removed hotel: roundup entries ${entriesRemoved} · comparison/toc/related rows ${listRows}`);
console.log(`review files deleted ${deleted} (${touched.length} slugs × locales) · hotel-coords rows removed ${rows}`);
if (countNotes.length) {
  console.log(`\nprose that still names the old count — edit by hand (${countNotes.length}):`);
  for (const c of countNotes) console.log('   ' + c);
}
if (leftovers.length) {
  console.log(`\nfiles that still mention a merged or removed slug after the pass (${leftovers.length}):`);
  for (const l of leftovers.slice(0, 20)) console.log('   ' + l);
}
if (!APPLY) console.log('\nDRY RUN — nothing written. Re-run with --apply.');
